"""Generate src/pbix_mcp/dax/_collation_data.py from Microsoft's published
"Windows Server 2008 Sorting Weight Table" (download id 10921, file
"Windows Server 2008 Sorting Weight Table.txt", sha256 b3b18105...0c75).

The table is not committed; pass its path:

    python gen_collation_data.py "<path>\\Windows Server 2008 Sorting Weight Table.txt"

Only three sections of the table are read, the ones that apply to a locale
with no exception or compression table of its own (en-US, 0x0409, has none):

- SORTKEY\\DEFAULT: code point, script member (SM), alphabetic weight (AW),
  diacritic weight (DW), case weight (CW) -- [MS-UCODEREF] 3.1.5.2.3.
- SORTTABLES\\EXPANSION: a code point that weighs as two others
  ([MS-UCODEREF] 3.1.5.2.11 GetExpandedCharacters); looked up only for code
  points the default table does not list (3.1.5.2.9 GetCharacterWeights).
- SORTTABLES\\COMPATIBILITY: "code points considered to be equivalent to other
  code points in the default table" (the section's own header). The
  pseudocode does not mention it; Desktop's answers (b181: U+037E = ";",
  U+1F71 = U+03AC) show it applies, so such a code point takes its target's
  weights.

Nothing else goes into the data: the corrections Desktop's answers call for
live in pbix_mcp/dax/collation.py, each with its evidence.

Output: WEIGHTS, the lzma-compressed, hex-encoded array of 65,536 records of
four bytes (SM, AW, DW, CW) -- all zero for a code unit the table does not
list -- and EXPANSIONS, {code point: (first, second)} for the code units that
weigh as two others (SM 2 in WEIGHTS).
"""
from __future__ import annotations

import hashlib
import lzma
import os
import sys

SHA256 = "b3b18105b03ff6f75c0efae9580a0a16a8b14a58cbb79e644f49067dbc2b0c75"
OUT = os.path.join(os.path.dirname(__file__), "..", "..", "..", "..",
                   "src", "pbix_mcp", "dax", "_collation_data.py")
EXPANSION_SM = 2      # [MS-UCODEREF] 3.1.5.2.4: SET constant EXPANSION to 2


def parse(path: str):
    raw = open(path, "rb").read()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != SHA256:
        raise SystemExit(f"unexpected table (sha256 {digest})")
    default: dict[int, tuple] = {}
    expansion: dict[int, tuple] = {}
    compat: dict[int, int] = {}
    section = None
    for line in raw.decode("utf-8", "replace").split("\n"):
        body = line.split(";", 1)[0].strip()
        if not body:
            continue
        f = body.split()
        if not f[0].lower().startswith("0x"):
            # a label ([MS-UCODEREF] 3.1.5.2.3: "labels are any field that
            # does not begin with a numerical (0xNNNN) value")
            label = f[0]
            if label == "DEFAULT" and section == "SORTKEY":
                section = "DEFAULT"
            elif label in ("LCID", "TWO", "THREE", "FOUR", "FIVE", "SIX", "SEVEN", "EIGHT"):
                pass        # subsections of COMPRESSION / EXCEPTION
            else:
                section = label
            continue
        if section == "DEFAULT":
            cp = int(f[0], 16)
            if cp in default:
                raise SystemExit(f"{cp:#06x} listed twice")
            default[cp] = tuple(int(x) for x in f[1:5])
        elif section == "EXPANSION":
            expansion[int(f[0], 16)] = (int(f[1], 16), int(f[2], 16))
        elif section == "COMPATIBILITY":
            compat[int(f[0], 16)] = int(f[1], 16)
    return default, expansion, compat


def build(path: str) -> tuple[bytes, dict]:
    default, expansion, compat = parse(path)
    table = bytearray(4 * 0x10000)
    exp_out: dict[int, tuple] = {}
    for cp in range(0x10000):
        src = cp
        if src not in default and src in compat:
            src = compat[src]
        if src in default:
            table[4 * cp:4 * cp + 4] = bytes(default[src])
        elif src in expansion:
            table[4 * cp] = EXPANSION_SM
            exp_out[cp] = expansion[src]
    return bytes(table), exp_out


def main(path: str) -> None:
    table, exp = build(path)
    blob = lzma.compress(table, preset=9 | lzma.PRESET_EXTREME).hex()
    rows = [blob[i:i + 112] for i in range(0, len(blob), 112)]
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write('"""Text collation data, generated by docs/reverse-engineering/experiments/\n'
                 '2026-10-19-clean-room-collation/gen_collation_data.py from Microsoft\'s published\n'
                 '"Windows Server 2008 Sorting Weight Table" (SORTKEY DEFAULT, EXPANSION and\n'
                 'COMPATIBILITY). Do not edit; see pbix_mcp.dax.collation."""\n')
        fh.write("# 65,536 records (SM, AW, DW, CW), lzma, hex\n")
        fh.write("WEIGHTS = (\n")
        for r in rows:
            fh.write(f'    "{r}"\n')
        fh.write(")\n")
        fh.write("# code unit -> the two code points it weighs as\n")
        fh.write("EXPANSIONS = {\n")
        for cp in sorted(exp):
            a, b = exp[cp]
            fh.write(f"    {cp:#06x}: ({a:#06x}, {b:#06x}),\n")
        fh.write("}\n")
    print(f"wrote {OUT}: {len(rows)} rows, {len(exp)} expansions")


if __name__ == "__main__":
    main(sys.argv[1])
