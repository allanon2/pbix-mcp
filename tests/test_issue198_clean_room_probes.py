def _eval(expr):
    try:
        got = de.DAXEngine()._eval_expr(expr, de.DAXContext(MODEL, {}))
    except Exception:
        return "ERR"
    if isinstance(got, bool):
        got = int(got)
    if isinstance(got, float) and got.is_integer():
        got = int(got)
    return str(got)


@pytest.mark.parametrize("pid,expr,want", PROBES, ids=[p[0] for p in PROBES])
def test_desktop(pid, expr, want):
    assert _eval(expr) == want


